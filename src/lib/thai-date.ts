/**
 * "วันนี้" ตามเวลาไทย
 *
 * ทำไมต้องมี: เซิร์ฟเวอร์บน Vercel รันด้วย TZ=UTC ดังนั้น
 * `new Date().toISOString().split('T')[0]` คือวันที่ตาม UTC ไม่ใช่วันที่ไทย
 * ช่วงเวลาไทย 00:00–06:59 จะยังนับเป็น "เมื่อวาน" (UTC+7)
 *
 * ผลที่ตามมาไม่ใช่แค่แสดงผลเพี้ยน: received_date ถูกส่งเข้า
 * next_document_display_no() ซึ่งออกเลขที่เอกสารตามเดือนของวันนั้น เอกสารที่
 * ลงทะเบียนเวลา 00:10 ของวันที่ 1 กันยายน จึงได้เลขของเดือนสิงหาคม
 *
 * ตรวจข้อมูลจริงแล้วยังไม่เคยเกิด (เอกสารทั้งหมดถูกสร้างช่วง 08:00–17:00 ไทย
 * = UTC 01:00–10:00 ซึ่งอยู่นอกช่วงที่เพี้ยน) แก้ไว้ก่อนที่กะเช้าหรืองาน
 * แมสเซนเจอร์รอบเช้ามืดจะทำให้มันทำงาน
 *
 * ฝั่ง browser ไม่ต้องใช้ไฟล์นี้ — เครื่องผู้ใช้อยู่ไทยอยู่แล้ว จึงใช้
 * getFullYear()/getMonth()/getDate() ตามแบบที่ recipient/tracking ทำได้เลย
 */

const BANGKOK_DATE = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Asia/Bangkok',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});

/** วันที่ไทยของช่วงเวลาที่ให้มา (ค่าเริ่มต้น = เดี๋ยวนี้) ในรูป YYYY-MM-DD */
export function bangkokDate(at: Date = new Date()): string {
  return BANGKOK_DATE.format(at);
}
